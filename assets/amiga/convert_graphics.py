def asm2bin(bank,output_dir,split):
    banko = bank.parent / f"{bank.stem}.o"
    banke = bank.parent / f"{bank.stem}"
    cmd = ["m68k-amigaos-as","-o",banko,bank]
    subprocess.run(cmd,check=True)
    # link the result. Not necessary when generation is OK, but
    # not everything is solved (dangling references), we'll detect it
    cmd = ["m68k-amigaos-ld","-o",banke,banko]
    subprocess.run(cmd,check=True)
    prefix = str(output_dir / f"{bank.stem}")

    bankbin = pathlib.Path(prefix if not split else prefix+"_full")
    cmd = ["m68k-amigaos-objcopy","-O","binary",banke,bankbin]
    subprocess.run(cmd,check=True)
    if split:
        # useful for sprite data files. The huge number of cluts in this game + sprites
        # creates a header of 0x40000 bytes where chipmem is not necessary. Besides, it's slower
        # to access all the pointers. It will be slightly more difficult to relocate when it's in 2 different zones
        # but it doesn't matter considering the chipmem we save
        with bankbin.open("rb") as f:
            split_offset = struct.unpack(">I",f.read(4))[0]
            header = f.read(split_offset)
            bitmap = f.read()
        header_file = pathlib.Path(prefix+"_header")
        with header_file.open("wb") as f:
            f.write(header)
        bitmap_file = pathlib.Path(prefix+"_bitmap")
        with bitmap_file.open("wb") as f:
            f.write(bitmap)
        bankbin.unlink()

